import { $, browser, expect } from "@wdio/globals";

// The tests run serially in one Tauri process. Reusing these records lets later journeys prove
// that data created through the UI remains available through the real persistence layer.
const patientName = "E2E Alex Smith";
const updatedPatientName = "E2E Alex Taylor";
const presetName = "E2E Upper Limb Rehab";
const duplicatedPresetName = `${presetName} (Copy)`;

// Native commands return JSON. These local types describe only the fields this spec needs, keeping
// the E2E test independent from frontend implementation modules.
type PersistedPatient = { id: string; displayName: string };
type PersistedPreset = { id: string; name: string };
type DashboardOverview = {
  todaysSchedule: Array<{ patientId: string; patientDisplayName: string }>;
};

async function clickButton(label: string) {
  // Waiting for clickability makes dialog transitions deterministic on slower CI machines.
  const button = await $(`button=${label}`);
  await button.waitForClickable();
  await button.click();
}

async function getPatient(name = patientName) {
  // Reading through Tauri, rather than React state, proves that the earlier UI action reached Rust
  // and SQLite. It also gives later tests the UUID generated by the backend.
  const patients = await browser.tauri.execute(
    ({ core }) => core.invoke("get_patients") as Promise<PersistedPatient[]>,
  );
  const patient = patients.find((candidate) => candidate.displayName === name);
  if (!patient) throw new Error(`Expected persisted patient '${name}'`);
  return patient;
}

async function getPreset(patientId: string, name = presetName) {
  // Look up the persisted preset UUID needed to record a completed session later in the suite.
  const presets = await browser.tauri.execute(
    ({ core }, id) => core.invoke("get_presets", { patientId: id }) as Promise<PersistedPreset[]>,
    patientId,
  );
  const preset = presets.find((candidate) => candidate.name === name);
  if (!preset) throw new Error(`Expected persisted preset '${name}'`);
  return preset;
}

async function openModifyPatient(patientId: string) {
  // Radix renders this dropdown through a portal. WebKitGTK does not reliably hit-test that portal,
  // so dispatch the same pointer interaction from inside the renderer.
  await browser.execute((id) => {
    const trigger = document.querySelector<HTMLElement>(`[data-testid="patient-actions-${id}"]`);
    if (!trigger) throw new Error(`Patient actions trigger '${id}' was not found`);
    trigger.dispatchEvent(
      new PointerEvent("pointerdown", {
        bubbles: true,
        button: 0,
        pointerType: "mouse",
      }),
    );
    trigger.click();
  }, patientId);

  const actionSelector = `[data-testid="modify-patient-${patientId}"]`;
  await $(actionSelector).waitForDisplayed();
  // This still invokes the real menu item's React handler; it only avoids a driver-level issue.
  await browser.execute((selector) => {
    const action = document.querySelector<HTMLElement>(selector);
    if (!action) throw new Error(`Patient modify action '${selector}' was not found`);
    action.click();
  }, actionSelector);
}

describe("critical patient and preset journeys", () => {
  it("gates session creation until a patient exists", async () => {
    // Every run starts with a fresh temporary SQLite database, so no patient should exist yet.
    await expect($("h1=Welcome back, Dr. Smith")).toBeDisplayed();
    await expect($("div*=No patients have been added yet.")).toBeDisplayed();
    await expect($("button=Add Session")).toBeDisabled();
  });

  it("persists a patient and preset through the real Tauri backend", async () => {
    // Create the patient through the same dialog a clinician uses, including optional notes.
    await clickButton("Add Patient");
    await $("#add-patient-display-name").setValue(patientName);
    await $("#add-patient-clinical-notes").setValue("Stroke rehabilitation");
    await clickButton("Create Patient");

    const patientCell = await $(`span=${patientName}`);
    await expect(patientCell).toBeDisplayed();
    await expect($("button=Add Session")).toBeEnabled();
    await patientCell.click();

    // A new patient begins with empty history but can navigate directly back to their presets.
    await expect($("h1=Choose a preset")).toBeDisplayed();
    await expect($(`p=${patientName}`)).toBeDisplayed();

    await clickButton("Patient History");
    await expect($("h1=Patient history")).toBeDisplayed();
    await expect($("h2=No completed sessions yet")).toBeDisplayed();
    await clickButton("Go to presets");

    // Create a custom preset entirely through the UI.
    await clickButton("Add Preset");
    const customPresetMode = await $("button*=Create Custom Preset");
    await customPresetMode.waitForClickable();
    await customPresetMode.click();
    await $("#preset-name").setValue(presetName);
    await clickButton("Create Preset");

    // Movement creation and recognition must stay gated until resting-pose calibration is done.
    await expect($(`h1=${presetName} Mappings`)).toBeDisplayed();
    await expect($("h2=Default resting state required")).toBeDisplayed();
    await expect($("button=Add New Movement")).toBeDisabled();
    await expect($("button=Test Recognition")).toBeDisabled();

    // Navigate back and verify that both newly persisted records remain visible.
    await clickButton("Back");
    await expect($(`h3=${presetName}`)).toBeDisplayed();
    await expect($(`[aria-label="Select ${presetName}"]`)).toBeDisplayed();
    await clickButton("Back");

    await expect($(`span=${patientName}`)).toBeDisplayed();
    await expect($("button=Add Session")).toBeEnabled();
  });

  it("validates and persists a scheduled session", async () => {
    // Exercise the form's sad path before supplying the required patient.
    await clickButton("Add Session");
    await clickButton("Schedule Session");
    await expect($("p=Select a patient, date, and time.")).toBeDisplayed();

    const patientSelect = await $("#session-patient");
    await patientSelect.click();
    await browser.keys(["\uE015", "\uE007"]);
    await expect(patientSelect).toHaveText(patientName);
    await clickButton("Schedule Session");
    await expect($("h2=Add Session")).not.toBeDisplayed();

    // Query a broad range so this assertion remains stable if CI runs around local midnight.
    const patient = await getPatient();
    const now = Date.now();
    const overview = await browser.tauri.execute(
      ({ core }, patientId, rangeStart, rangeEnd) =>
        core
          .invoke("get_dashboard_overview", {
            dayStartMs: rangeStart,
            dayEndMs: rangeEnd,
          })
          .then((result) => result as DashboardOverview)
          .then((result) => ({
            ...result,
            todaysSchedule: result.todaysSchedule.filter(
              (session) => session.patientId === patientId,
            ),
          })),
      patient.id,
      now - 86_400_000,
      now + 172_800_000,
    );
    expect(overview.todaysSchedule).toHaveLength(1);
    expect(overview.todaysSchedule[0]?.patientDisplayName).toBe(patientName);
  });

  it("duplicates and deletes a preset through confirmation dialogs", async () => {
    // Exercise both operations through their user-facing confirmation dialogs.
    await $(`span=${patientName}`).click();
    await expect($(`h3=${presetName}`)).toBeDisplayed();

    await $(`[title="Duplicate ${presetName}"]`).click();
    await expect($("h2=Duplicate preset?")).toBeDisplayed();
    await clickButton("Duplicate preset");
    await expect($(`h3=${duplicatedPresetName}`)).toBeDisplayed();

    await $(`[title="Delete ${duplicatedPresetName}"]`).click();
    await expect($("h2=Delete preset?")).toBeDisplayed();
    await clickButton("Delete preset");
    await expect($(`h3=${duplicatedPresetName}`)).not.toExist();
    await expect($(`h3=${presetName}`)).toBeDisplayed();
  });

  it("loads a completed session recorded by the real backend", async () => {
    const patient = await getPatient();
    const preset = await getPreset(patient.id);
    const endedAtMs = Date.now();

    // Starting a real live session requires a webcam, OS permissions and timed pose input. Seed
    // only that hardware-bound outcome through the production Tauri command. Rust validation,
    // snapshotting, SQLite persistence, history loading and React rendering all remain real.
    await browser.tauri.execute(
      ({ core }, session) => core.invoke("record_completed_session", { session }),
      {
        sessionId: `e2e-session-${endedAtMs}`,
        patientId: patient.id,
        presetId: preset.id,
        startedAtMs: endedAtMs - 120_000,
        endedAtMs,
        triggerCountsByMapping: {},
      },
    );

    // The history page should replace its empty state with the persisted session summary.
    await clickButton("Patient History");
    await expect($("h1=Patient history")).toBeDisplayed();
    await expect($("p=Completed sessions")).toBeDisplayed();
    await expect($(`td=${presetName}`)).toBeDisplayed();
    await expect($("td=2m 00s")).toBeDisplayed();
    await expect($("h2=No completed sessions yet")).not.toExist();

    await clickButton("Back to presets");
    await clickButton("Back");
  });

  it("updates and deletes a patient from the dashboard", async () => {
    const patient = await getPatient();
    await openModifyPatient(patient.id);

    // Verify that an update is reflected immediately in the dashboard table.
    await expect($("h2=Modify Patient")).toBeDisplayed();
    await $("#modify-patient-display-name").setValue(updatedPatientName);
    await clickButton("Save changes");
    await expect($(`span=${updatedPatientName}`)).toBeDisplayed();

    // Deletion uses a nested confirmation dialog because it also removes related patient data.
    await openModifyPatient(patient.id);
    await clickButton("Delete Patient");
    await expect($("h2=Delete Patient?")).toBeDisplayed();
    // Click inside the renderer to avoid the same WebKitGTK portal hit-testing limitation.
    await browser.execute(() => {
      const dialog = Array.from(document.querySelectorAll<HTMLElement>('[role="dialog"]')).find(
        (candidate) => candidate.querySelector("h2")?.textContent?.trim() === "Delete Patient?",
      );
      const confirmation = Array.from(
        dialog?.querySelectorAll<HTMLButtonElement>("button") ?? [],
      ).find((button) => button.textContent?.trim() === "Delete Patient");
      if (!confirmation) throw new Error("Delete patient confirmation was not found");
      confirmation.click();
    });

    // Deleting the only patient should restore the dashboard's original session gate.
    await expect($(`span=${updatedPatientName}`)).not.toExist();
    await expect($("button=Add Session")).toBeDisabled();
  });

  it("recovers from an unknown route", async () => {
    // Setting the hash directly simulates an old bookmark or malformed internal link.
    await browser.execute(() => {
      window.location.hash = "/a-route-that-does-not-exist";
    });
    await expect($("h1=This page does not exist")).toBeDisplayed();
    // Recovery must return to a usable dashboard, not merely change the URL.
    const dashboardLink = await $("a=Return to dashboard");
    await dashboardLink.waitForClickable();
    await dashboardLink.click();
    await expect($("h1=Welcome back, Dr. Smith")).toBeDisplayed();
  });
});
